-- Extensión de la fase 8: pedidos previos a la venta.
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    customer_id BIGINT,
    created_by BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','converted','cancelled')),
    currency CHAR(3) NOT NULL,
    total NUMERIC(14,2) NOT NULL CHECK (total > 0),
    sale_id BIGINT,
    cancel_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id,id),
    UNIQUE (company_id,sale_id),
    FOREIGN KEY (company_id,customer_id) REFERENCES customers(company_id,id),
    FOREIGN KEY (company_id,created_by) REFERENCES users(company_id,id),
    FOREIGN KEY (company_id,sale_id) REFERENCES sales(company_id,id),
    CHECK ((status = 'converted') = (sale_id IS NOT NULL)),
    CHECK ((status = 'cancelled') = (cancel_reason IS NOT NULL))
);

CREATE TABLE order_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name_snapshot VARCHAR(180) NOT NULL,
    sku_snapshot VARCHAR(80) NOT NULL,
    quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMERIC(14,2) NOT NULL CHECK (line_total >= 0),
    UNIQUE (company_id,order_id,product_id),
    FOREIGN KEY (company_id,order_id) REFERENCES orders(company_id,id),
    FOREIGN KEY (company_id,product_id) REFERENCES products(company_id,id)
);

CREATE INDEX ix_orders_company_created ON orders(company_id,created_at DESC,id DESC);
CREATE INDEX ix_orders_company_creator ON orders(company_id,created_by,created_at DESC);
