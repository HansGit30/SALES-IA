-- SalesIA Enterprise — esquema inicial PostgreSQL (Fase 04)
-- Ejecutar sobre una base vacía. Contraseñas siempre se almacenan como hash.

CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'PEN',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    role_id BIGINT NOT NULL REFERENCES roles(id),
    email VARCHAR(254) NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, email),
    UNIQUE (company_id, id)
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    name VARCHAR(180) NOT NULL,
    email VARCHAR(254),
    phone VARCHAR(40),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, id)
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    name VARCHAR(120) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (company_id, name),
    UNIQUE (company_id, id)
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    category_id BIGINT,
    sku VARCHAR(80) NOT NULL,
    name VARCHAR(180) NOT NULL,
    description TEXT,
    unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (company_id, sku),
    UNIQUE (company_id, id),
    FOREIGN KEY (company_id, category_id) REFERENCES categories(company_id, id)
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    user_id BIGINT,
    full_name VARCHAR(160) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (company_id, id),
    UNIQUE (company_id, user_id),
    FOREIGN KEY (company_id, user_id) REFERENCES users(company_id, id)
);

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    customer_id BIGINT,
    seller_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'confirmed' CHECK (status IN ('draft','confirmed','voided')),
    currency CHAR(3) NOT NULL,
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
    discount_total NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount_total >= 0),
    tax_total NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (tax_total >= 0),
    total NUMERIC(14,2) NOT NULL CHECK (total >= 0),
    void_reason TEXT,
    sold_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    voided_at TIMESTAMPTZ,
    UNIQUE (company_id, id),
    FOREIGN KEY (company_id, customer_id) REFERENCES customers(company_id, id),
    FOREIGN KEY (company_id, seller_id) REFERENCES employees(company_id, id),
    FOREIGN KEY (company_id, created_by) REFERENCES users(company_id, id),
    CHECK ((status <> 'voided') OR (void_reason IS NOT NULL AND voided_at IS NOT NULL))
);

CREATE TABLE sale_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name_snapshot VARCHAR(180) NOT NULL,
    sku_snapshot VARCHAR(80) NOT NULL,
    quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
    discount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    tax NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (tax >= 0),
    line_total NUMERIC(14,2) NOT NULL CHECK (line_total >= 0),
    FOREIGN KEY (company_id, sale_id) REFERENCES sales(company_id, id),
    FOREIGN KEY (company_id, product_id) REFERENCES products(company_id, id)
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    sale_id BIGINT NOT NULL,
    method VARCHAR(40) NOT NULL,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'completed' CHECK (status IN ('pending','completed','refunded')),
    paid_at TIMESTAMPTZ,
    FOREIGN KEY (company_id, sale_id) REFERENCES sales(company_id, id)
);

CREATE TABLE inventory (
    company_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (company_id, product_id),
    FOREIGN KEY (company_id, product_id) REFERENCES products(company_id, id)
);

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    sale_id BIGINT,
    movement_type VARCHAR(24) NOT NULL CHECK (movement_type IN ('opening','purchase','sale','sale_void','adjustment')),
    quantity_delta NUMERIC(14,3) NOT NULL CHECK (quantity_delta <> 0),
    reason TEXT,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (company_id, product_id) REFERENCES products(company_id, id),
    FOREIGN KEY (company_id, sale_id) REFERENCES sales(company_id, id),
    FOREIGN KEY (company_id, created_by) REFERENCES users(company_id, id)
);

CREATE TABLE datasets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    name VARCHAR(160) NOT NULL,
    source VARCHAR(40) NOT NULL,
    filters JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (company_id, created_by) REFERENCES users(company_id, id),
    UNIQUE (company_id, id)
);

CREATE TABLE dataset_variables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    dataset_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    data_type VARCHAR(24) NOT NULL CHECK (data_type IN ('quantitative_discrete','quantitative_continuous','qualitative_nominal','qualitative_ordinal')),
    unit VARCHAR(40),
    FOREIGN KEY (company_id, dataset_id) REFERENCES datasets(company_id, id),
    UNIQUE (dataset_id, name)
);

CREATE TABLE observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    dataset_id BIGINT NOT NULL,
    variable_id BIGINT NOT NULL REFERENCES dataset_variables(id),
    numeric_value NUMERIC(18,6),
    text_value TEXT,
    observed_at TIMESTAMPTZ,
    source_ref VARCHAR(160),
    FOREIGN KEY (company_id, dataset_id) REFERENCES datasets(company_id, id),
    CHECK (num_nonnulls(numeric_value, text_value) = 1)
);

CREATE TABLE statistical_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    dataset_id BIGINT NOT NULL,
    analysis_type VARCHAR(40) NOT NULL,
    parameters JSONB NOT NULL DEFAULT '{}'::jsonb,
    result JSONB NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (company_id, dataset_id) REFERENCES datasets(company_id, id),
    FOREIGN KEY (company_id, created_by) REFERENCES users(company_id, id),
    UNIQUE (company_id, id)
);

CREATE TABLE statistical_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    analysis_id BIGINT NOT NULL,
    variable_id BIGINT NOT NULL REFERENCES dataset_variables(id),
    metric VARCHAR(60) NOT NULL,
    numeric_value NUMERIC(20,8),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    FOREIGN KEY (company_id, analysis_id) REFERENCES statistical_analyses(company_id, id)
);

CREATE TABLE bayes_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    analysis_id BIGINT NOT NULL,
    event_a VARCHAR(160) NOT NULL,
    event_b VARCHAR(160) NOT NULL,
    p_a NUMERIC(12,10) NOT NULL CHECK (p_a BETWEEN 0 AND 1),
    p_b_given_a NUMERIC(12,10) NOT NULL CHECK (p_b_given_a BETWEEN 0 AND 1),
    p_b NUMERIC(12,10) NOT NULL CHECK (p_b > 0 AND p_b <= 1),
    p_a_given_b NUMERIC(12,10) NOT NULL CHECK (p_a_given_b BETWEEN 0 AND 1),
    FOREIGN KEY (company_id, analysis_id) REFERENCES statistical_analyses(company_id, id)
);

CREATE TABLE random_variables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    name VARCHAR(140) NOT NULL,
    distribution VARCHAR(40) NOT NULL,
    parameters JSONB NOT NULL,
    description TEXT,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (company_id, created_by) REFERENCES users(company_id, id)
);

CREATE TABLE insights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    analysis_id BIGINT,
    rule_code VARCHAR(80) NOT NULL,
    title VARCHAR(180) NOT NULL,
    message TEXT NOT NULL,
    evidence JSONB NOT NULL,
    severity VARCHAR(20) NOT NULL DEFAULT 'info',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (company_id, analysis_id) REFERENCES statistical_analyses(company_id, id)
);

CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    report_type VARCHAR(60) NOT NULL,
    parameters JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (company_id, created_by) REFERENCES users(company_id, id)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    user_id BIGINT,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id VARCHAR(100),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (company_id, user_id) REFERENCES users(company_id, id)
);

CREATE INDEX ix_sales_company_sold_at ON sales(company_id, sold_at);
CREATE INDEX ix_sales_company_status_sold_at ON sales(company_id, status, sold_at);
CREATE INDEX ix_sales_company_customer ON sales(company_id, customer_id);
CREATE INDEX ix_sales_company_seller ON sales(company_id, seller_id);
CREATE INDEX ix_sale_details_company_sale ON sale_details(company_id, sale_id);
CREATE INDEX ix_movements_company_product_date ON inventory_movements(company_id, product_id, created_at);
CREATE INDEX ix_analyses_company_created ON statistical_analyses(company_id, created_at DESC);
CREATE INDEX ix_audit_company_created ON audit_logs(company_id, created_at DESC);


